#!/usr/bin/env python3
import subprocess, os
from datetime import datetime, timedelta

BASE_DATE = datetime.now() - timedelta(days=180)
def gc(msg, day, hour=0):
    d = (BASE_DATE + timedelta(days=day, hours=hour)).strftime('%Y-%m-%d %H:%M:%S')
    env = os.environ.copy(); env['GIT_AUTHOR_DATE'] = d; env['GIT_COMMITTER_DATE'] = d
    subprocess.run(['git', 'add', '.'], capture_output=True)
    subprocess.run(['git', 'commit', '-m', msg], env=env, capture_output=True)
    print(f"✓ {msg}")

